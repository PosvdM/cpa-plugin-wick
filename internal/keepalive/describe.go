package keepalive

import (
	"regexp"
	"strings"
	"unicode/utf8"

	"github.com/tidwall/gjson"
)

// maxPromptRunes bounds the first prompt kept for the status API.
const maxPromptRunes = 200

// Claude Code writes the working directory into the environment section of
// the system prompt, as "Primary working directory: <path>" and, in older
// versions and some subagents, "Working directory: <path>".
var workDirPattern = regexp.MustCompile(`(?m)^[ \t]*(?:-[ \t]*)?(?:Primary working directory|Working directory):[ \t]*([^\r\n]+)`)

var (
	reminderPattern    = regexp.MustCompile(`(?s)<system-reminder>.*?(?:</system-reminder>|$)`)
	commandNamePattern = regexp.MustCompile(`(?s)<command-name>(.*?)</command-name>`)
	commandArgsPattern = regexp.MustCompile(`(?s)<command-args>(.*?)</command-args>`)
	spacePattern       = regexp.MustCompile(`\s+`)
)

// workingDirectory returns the working directory named in the system prompt,
// or "" when there is none.
func workingDirectory(body []byte) string {
	var dir string
	visit := func(text string) bool {
		if m := workDirPattern.FindStringSubmatch(text); m != nil {
			// An environment update appends " (was <old path>)".
			dir, _, _ = strings.Cut(m[1], " (was ")
			dir = strings.TrimSpace(dir)
		}
		return dir == ""
	}
	system := gjson.GetBytes(body, "system")
	if system.IsArray() {
		system.ForEach(func(_, block gjson.Result) bool { return visit(block.Get("text").String()) })
	} else {
		visit(system.String())
	}
	return dir
}

// firstPrompt returns what the user typed first in the conversation, on one
// line: the first user text that is not injected by Claude Code, such as a
// system reminder or the output of a local command. A slash command is shown
// as its name and arguments.
func firstPrompt(body []byte) string {
	var prompt string
	gjson.GetBytes(body, "messages").ForEach(func(i, msg gjson.Result) bool {
		if i.Int() >= 10 {
			return false
		}
		if msg.Get("role").String() != "user" {
			return true
		}
		content := msg.Get("content")
		if content.Type == gjson.String {
			prompt = promptText(content.String())
			return prompt == ""
		}
		content.ForEach(func(_, block gjson.Result) bool {
			if block.Get("type").String() == "text" {
				prompt = promptText(block.Get("text").String())
			}
			return prompt == ""
		})
		return prompt == ""
	})
	return truncate(prompt, maxPromptRunes)
}

func promptText(text string) string {
	text = strings.TrimSpace(reminderPattern.ReplaceAllString(text, ""))
	if name := commandNamePattern.FindStringSubmatch(text); name != nil {
		command := strings.TrimSpace(name[1])
		if args := commandArgsPattern.FindStringSubmatch(text); args != nil {
			command += " " + args[1]
		}
		text = command
	}
	if strings.HasPrefix(text, "<local-command-") || strings.HasPrefix(text, "<bash-") || strings.HasPrefix(text, "Caveat: The messages below were generated by the user while running local commands") {
		return ""
	}
	return strings.TrimSpace(spacePattern.ReplaceAllString(text, " "))
}

// truncate shortens s to at most n runes, ending with an ellipsis when cut.
func truncate(s string, n int) string {
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	runes := []rune(s)
	return strings.TrimSpace(string(runes[:n-1])) + "…"
}
